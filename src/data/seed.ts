function step(
  id: string,
  prompt: string,
  correct: string,
  incorrect: string,
  explanation: string,
): Step {
  return {
    id,
    prompt,
    options: [
      {
        id: id + 'a',
        text: incorrect,
        score: 0,
        feedback: 'Revisa esta decisión. ' + explanation,
      },
      {
        id: id + 'b',
        text: correct,
        score: 100,
        feedback: 'Correcto. ' + explanation,
      },
    ],
  }
}
